"""
Equilibrium Map SQL Exporter

Exports all equilibrium maps for all metal-ligand pairs in the VLM table to a single SQL file.

SQL Schema:
- eq_map_collection: one row per metal-ligand pair
- eq_map: one row per condition iteration  
- eq_network: one row per connected component
- eq_node: one row per VLM entry in a network
- eq_edge: one row per edge (shared species)
- eq_node_species: junction table for species per node (LHS/RHS)
- eq_edge_species: junction table for shared species per edge

The SQL output can be imported into SQLite for later pipeline stages.

Usage:
    python equilibrium_map_sql_exporter.py
"""
