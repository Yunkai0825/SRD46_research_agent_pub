SQL_SCHEMA = """
-- Equilibrium Map SQL Schema
-- Generated by equilibrium_map_sql_exporter.py

-- Pragma for better performance
PRAGMA journal_mode=WAL;
PRAGMA synchronous=NORMAL;

-- =============================================================================
-- Collection table: one row per metal-ligand pair
-- =============================================================================
CREATE TABLE IF NOT EXISTS eq_map_collection (
    collection_id INTEGER PRIMARY KEY AUTOINCREMENT,
    metal_id INTEGER NOT NULL,
    ligand_id INTEGER NOT NULL,
    metal_name TEXT,
    ligand_name TEXT,
    total_entries INTEGER DEFAULT 0,
    total_networks INTEGER DEFAULT 0,
    iterations_count INTEGER DEFAULT 0,
    unassigned_count INTEGER DEFAULT 0,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UNIQUE(metal_id, ligand_id)
);

-- =============================================================================
-- Map table: one row per condition iteration
-- =============================================================================
CREATE TABLE IF NOT EXISTS eq_map (
    map_id INTEGER PRIMARY KEY AUTOINCREMENT,
    collection_id INTEGER NOT NULL,
    map_key TEXT NOT NULL,
    iteration INTEGER DEFAULT 0,
    -- Condition bin
    condition_temperature REAL,
    condition_ionic_strength REAL,
    condition_temp_min REAL,
    condition_temp_max REAL,
    condition_ionic_min REAL,
    condition_ionic_max REAL,
    -- Counts
    entry_count INTEGER DEFAULT 0,
    network_count INTEGER DEFAULT 0,
    stray_count INTEGER DEFAULT 0,
    FOREIGN KEY (collection_id) REFERENCES eq_map_collection(collection_id),
    UNIQUE(collection_id, map_key)
);

-- =============================================================================
-- Network table: one row per connected component
-- =============================================================================
CREATE TABLE IF NOT EXISTS eq_network (
    network_db_id INTEGER PRIMARY KEY AUTOINCREMENT,
    map_id INTEGER NOT NULL,
    network_id INTEGER NOT NULL,  -- Local network ID within the map
    node_count INTEGER DEFAULT 0,
    edge_count INTEGER DEFAULT 0,
    FOREIGN KEY (map_id) REFERENCES eq_map(map_id),
    UNIQUE(map_id, network_id)
);

-- =============================================================================
-- Node table: one row per VLM entry in a network
-- =============================================================================
CREATE TABLE IF NOT EXISTS eq_node (
    node_db_id INTEGER PRIMARY KEY AUTOINCREMENT,
    network_db_id INTEGER NOT NULL,
    vlm_id INTEGER NOT NULL,
    entry_index INTEGER,
    metal_id INTEGER NOT NULL,
    ligand_id INTEGER NOT NULL,
    beta_definition_id INTEGER NOT NULL,
    beta_definition_name TEXT,
    equation_python TEXT,
    constant_type TEXT,
    constant_value REAL,
    temperature REAL,
    ionic_strength REAL,
    is_duplicate INTEGER DEFAULT 0,
    used_in_map INTEGER DEFAULT 1,
    FOREIGN KEY (network_db_id) REFERENCES eq_network(network_db_id)
);

-- Index for fast VLM lookups
CREATE INDEX IF NOT EXISTS idx_eq_node_vlm_id ON eq_node(vlm_id);
CREATE INDEX IF NOT EXISTS idx_eq_node_beta_id ON eq_node(beta_definition_id);

-- =============================================================================
-- Node species junction table
-- =============================================================================
CREATE TABLE IF NOT EXISTS eq_node_species (
    node_db_id INTEGER NOT NULL,
    species TEXT NOT NULL,
    side TEXT NOT NULL,  -- 'LHS', 'RHS', or 'BOTH'
    FOREIGN KEY (node_db_id) REFERENCES eq_node(node_db_id),
    PRIMARY KEY (node_db_id, species, side)
);

-- =============================================================================
-- Edge table: one row per edge (shared species)
-- =============================================================================
CREATE TABLE IF NOT EXISTS eq_edge (
    edge_db_id INTEGER PRIMARY KEY AUTOINCREMENT,
    network_db_id INTEGER NOT NULL,
    node1_vlm_id INTEGER NOT NULL,
    node2_vlm_id INTEGER NOT NULL,
    FOREIGN KEY (network_db_id) REFERENCES eq_network(network_db_id)
);

-- =============================================================================
-- Edge species junction table
-- =============================================================================
CREATE TABLE IF NOT EXISTS eq_edge_species (
    edge_db_id INTEGER NOT NULL,
    species TEXT NOT NULL,
    FOREIGN KEY (edge_db_id) REFERENCES eq_edge(edge_db_id),
    PRIMARY KEY (edge_db_id, species)
);

-- =============================================================================
-- Network species junction table (all species in network)
-- =============================================================================
CREATE TABLE IF NOT EXISTS eq_network_species (
    network_db_id INTEGER NOT NULL,
    species TEXT NOT NULL,
    FOREIGN KEY (network_db_id) REFERENCES eq_network(network_db_id),
    PRIMARY KEY (network_db_id, species)
);

-- =============================================================================
-- Stray VLM IDs table (entries not assigned to networks)
-- =============================================================================
CREATE TABLE IF NOT EXISTS eq_map_stray (
    map_id INTEGER NOT NULL,
    vlm_id INTEGER NOT NULL,
    FOREIGN KEY (map_id) REFERENCES eq_map(map_id),
    PRIMARY KEY (map_id, vlm_id)
);

-- =============================================================================
-- Unassigned VLM IDs table (entries not assigned after all iterations)
-- =============================================================================
CREATE TABLE IF NOT EXISTS eq_collection_unassigned (
    collection_id INTEGER NOT NULL,
    vlm_id INTEGER NOT NULL,
    FOREIGN KEY (collection_id) REFERENCES eq_map_collection(collection_id),
    PRIMARY KEY (collection_id, vlm_id)
);

-- =============================================================================
-- Debug/metadata table
-- =============================================================================
CREATE TABLE IF NOT EXISTS eq_export_metadata (
    key TEXT PRIMARY KEY,
    value TEXT
);
"""


