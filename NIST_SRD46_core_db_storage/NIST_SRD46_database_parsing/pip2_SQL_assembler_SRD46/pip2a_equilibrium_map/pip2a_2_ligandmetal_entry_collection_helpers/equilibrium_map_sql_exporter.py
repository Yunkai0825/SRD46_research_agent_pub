    """Debug report for VLM coverage."""
    
    # Counts
    total_vlm_entries: int = 0
    total_vlm_k_type: int = 0
    unique_metal_ligand_pairs: int = 0
    
    # Coverage
    vlm_assigned_to_networks: int = 0
    vlm_stray: int = 0
    vlm_unassigned: int = 0
    
    # Validation
    valid_beta_count: int = 0
    invalid_beta_vlm_ids: List[int] = None
    valid_metal_count: int = 0
    invalid_metal_vlm_ids: List[int] = None
    valid_ligand_count: int = 0
    invalid_ligand_vlm_ids: List[int] = None
    
    # No-species betas (skipped)
