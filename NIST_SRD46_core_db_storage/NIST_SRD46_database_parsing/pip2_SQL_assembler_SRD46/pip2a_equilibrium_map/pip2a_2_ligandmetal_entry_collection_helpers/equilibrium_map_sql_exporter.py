def export_equilibrium_maps_to_sql(
    output_path: Path = DEFAULT_SQL_PATH,
    max_pairs: Optional[int] = None,
    max_iterations: int = 10000,
) -> Tuple[Path, DebugReport]:
    """Export all equilibrium maps to SQL database.
    
    Args:
        output_path: Path to output SQLite database
        max_pairs: Optional limit for testing
        max_iterations: Maximum iterations per pair (default 10000)
        
    Returns:
        Tuple of (database path, debug report)
    """
    logger.info(f"export_equilibrium_maps_to_sql: output={output_path}, max_pairs={max_pairs}, max_iterations={max_iterations}")
    
    exporter = EquilibriumMapSQLExporter(output_path)
    
    try:
        exporter.open()
        logger.info("export_equilibrium_maps_to_sql: Database opened")
        
        report = exporter.export_all(max_pairs, max_iterations)
        exporter.save_debug_report()
        exporter.save_no_species_csv()
        
        # Save non-converged entries if any
        if report.vlm_unassigned > 0:
            exporter.save_non_converged_csv()
        
        logger.info(f"export_equilibrium_maps_to_sql: Export complete - coverage={report.vlm_assigned_to_networks}/{report.total_vlm_k_type}")
        
        print(f"\n{'='*60}")
        print("Export complete!")
        print(f"{'='*60}")
        print(f"Database: {output_path}")
        print(f"Total VLM (K-type): {report.total_vlm_k_type}")
        print(f"No-species (skipped): {report.no_species_vlm_count}")
        print(f"Assigned to networks: {report.vlm_assigned_to_networks}")
        print(f"Stray (duplicates): {report.vlm_stray}")
        print(f"Unassigned (non-converged): {report.vlm_unassigned}")
        coverage = report.vlm_assigned_to_networks / (report.total_vlm_k_type - report.no_species_vlm_count) * 100 if (report.total_vlm_k_type - report.no_species_vlm_count) > 0 else 0
        print(f"Coverage rate (excl. no-species): {coverage:.1f}%")
        print(f"Duration: {report.duration_seconds:.1f}s")
        print(f"{'='*60}")
        
        return output_path, report
        
    finally:
        exporter.close()


