class EquilibriumMapSQLExporter:
    """Exports equilibrium maps to SQLite database."""
    
    def __init__(self, db_path: Path = DEFAULT_SQL_PATH):
        self.db_path = db_path
        self.conn: Optional[sqlite3.Connection] = None
        self.debug_report = DebugReport()
        
        # Tracking sets
        self._assigned_vlm_ids: Set[int] = set()
        self._stray_vlm_ids: Set[int] = set()
        self._unassigned_vlm_ids: Set[int] = set()
        self._no_species_vlm_set: Set[int] = set()
    
    def open(self) -> None:
        """Open database connection and create schema."""
        self.db_path.parent.mkdir(parents=True, exist_ok=True)
        
        # Remove existing file if it exists
        if self.db_path.exists():
            self.db_path.unlink()
        
        self.conn = sqlite3.connect(str(self.db_path))
        self.conn.executescript(SQL_SCHEMA)
        self.conn.commit()
    
    def close(self) -> None:
        """Close database connection."""
        if self.conn:
            self.conn.close()
            self.conn = None
    
    def validate_vlm_entries(self) -> None:
        """Validate all VLM entries for valid beta, metal, ligand references."""
        logger.info("validate_vlm_entries: Starting VLM validation...")
        
        vlm_df = load_vlm_data()
        beta_df = load_beta_definitions()
        metals_df = load_metals()
        ligands_df = load_ligands()
        
        self.debug_report.total_vlm_entries = len(vlm_df)
        logger.debug(f"  Loaded {len(vlm_df)} total VLM entries")
        
        # Filter K-type only
        k_type_mask = vlm_df[VLM_COLS["constant_type"]] == CONSTANT_TYPE_K
        k_type_vlm = vlm_df[k_type_mask].copy()
        self.debug_report.total_vlm_k_type = len(k_type_vlm)
        logger.debug(f"  K-type entries: {len(k_type_vlm)}")
        
        # Check beta references
        beta_col = VLM_COLS["beta_id"]
        beta_ids = set(beta_df.index) if "beta_definitionID" in beta_df.columns else set(beta_df["beta_definitionID"])
        invalid_beta_mask = ~k_type_vlm[beta_col].isin(beta_ids)
        self.debug_report.invalid_beta_vlm_ids = list(k_type_vlm.loc[invalid_beta_mask, "verkn_ligand_metalID"])
        self.debug_report.valid_beta_count = len(beta_ids)
        logger.debug(f"  Beta validation: {len(beta_ids)} valid IDs, {len(self.debug_report.invalid_beta_vlm_ids)} invalid refs")
        
        # Check metal references
        metal_col = VLM_COLS["metal_id"]
        metal_ids = set(metals_df.index) if "metalID" in metals_df.columns else set(metals_df["metalID"])
        invalid_metal_mask = ~k_type_vlm[metal_col].isin(metal_ids)
        self.debug_report.invalid_metal_vlm_ids = list(k_type_vlm.loc[invalid_metal_mask, "verkn_ligand_metalID"])
        self.debug_report.valid_metal_count = len(metal_ids)
        logger.debug(f"  Metal validation: {len(metal_ids)} valid IDs, {len(self.debug_report.invalid_metal_vlm_ids)} invalid refs")
        
        # Check ligand references
        ligand_col = VLM_COLS["ligand_id"]
        ligand_ids = set(ligands_df.index) if "ligandenID" in ligands_df.columns else set(ligands_df["ligandenID"])
        invalid_ligand_mask = ~k_type_vlm[ligand_col].isin(ligand_ids)
        self.debug_report.invalid_ligand_vlm_ids = list(k_type_vlm.loc[invalid_ligand_mask, "verkn_ligand_metalID"])
        self.debug_report.valid_ligand_count = len(ligand_ids)
        logger.debug(f"  Ligand validation: {len(ligand_ids)} valid IDs, {len(self.debug_report.invalid_ligand_vlm_ids)} invalid refs")
        
        # Detect betas with no species (these VLM entries can never form nodes)
        logger.debug("  Detecting betas with no species...")
        no_species_beta_ids = set()
        for beta_id in beta_df.index:
            beta_row = beta_df.loc[beta_id]
            lhs, rhs, all_sp = extract_species_from_beta_definition(beta_row, int(beta_id))
            if len(all_sp) == 0:
                no_species_beta_ids.add(float(beta_id))
        
        self.debug_report.no_species_beta_ids = [int(b) for b in no_species_beta_ids]
        
        # Find VLM entries referencing no-species betas
        no_species_vlm_mask = k_type_vlm[beta_col].astype(float).isin(no_species_beta_ids)
        self.debug_report.no_species_vlm_ids = list(k_type_vlm.loc[no_species_vlm_mask, "verkn_ligand_metalID"])
        self.debug_report.no_species_vlm_count = len(self.debug_report.no_species_vlm_ids)
        self._no_species_vlm_set = set(self.debug_report.no_species_vlm_ids)
        
        logger.info(f"validate_vlm_entries: Validation complete")
        logger.info(f"  Total VLM entries: {self.debug_report.total_vlm_entries}")
        logger.info(f"  K-type VLM entries: {self.debug_report.total_vlm_k_type}")
        logger.info(f"  Invalid beta refs: {len(self.debug_report.invalid_beta_vlm_ids)}")
        logger.info(f"  Invalid metal refs: {len(self.debug_report.invalid_metal_vlm_ids)}")
        logger.info(f"  Invalid ligand refs: {len(self.debug_report.invalid_ligand_vlm_ids)}")
        logger.info(f"  No-species betas: {len(no_species_beta_ids)} (affects {self.debug_report.no_species_vlm_count} VLM entries)")
        
        print(f"Validation complete:")
        print(f"  Total VLM entries: {self.debug_report.total_vlm_entries}")
        print(f"  K-type VLM entries: {self.debug_report.total_vlm_k_type}")
        print(f"  Invalid beta refs: {len(self.debug_report.invalid_beta_vlm_ids)}")
        print(f"  Invalid metal refs: {len(self.debug_report.invalid_metal_vlm_ids)}")
        print(f"  Invalid ligand refs: {len(self.debug_report.invalid_ligand_vlm_ids)}")
        print(f"  No-species betas: {len(no_species_beta_ids)} (affects {self.debug_report.no_species_vlm_count} VLM entries)")
    
    def get_unique_metal_ligand_pairs(self) -> List[Tuple[int, int]]:
        """Get all unique metal-ligand pairs from VLM table (K-type only)."""
        vlm_df = load_vlm_data()
        
        # Filter K-type only
        k_type_mask = vlm_df[VLM_COLS["constant_type"]] == CONSTANT_TYPE_K
        k_type_vlm = vlm_df[k_type_mask]
        
        # Get unique pairs
        metal_col = VLM_COLS["metal_id"]
        ligand_col = VLM_COLS["ligand_id"]
        
        pairs = k_type_vlm[[metal_col, ligand_col]].drop_duplicates()
        result = list(pairs.itertuples(index=False, name=None))
        
        self.debug_report.unique_metal_ligand_pairs = len(result)
        return result
    
    def export_collection(self, collection: MetalLigandEquilibriumMapCollection) -> int:
        """Export a collection to the database.
        
        Returns:
            collection_id from the database
        """
        logger.debug(f"export_collection: M={collection.metal_id}, L={collection.ligand_id} - "
                     f"{collection.total_entries} entries, {len(collection.maps)} maps, "
                     f"{collection.total_networks} networks")
        
        cursor = self.conn.cursor()
        
        # Insert collection
        cursor.execute("""
            INSERT INTO eq_map_collection (
                metal_id, ligand_id, metal_name, ligand_name,
                total_entries, total_networks, iterations_count, unassigned_count
            ) VALUES (?, ?, ?, ?, ?, ?, ?, ?)
        """, (
            collection.metal_id,
            collection.ligand_id,
            collection.metal_name,
            collection.ligand_name,
            collection.total_entries,
            collection.total_networks,
            collection.iterations_count,
            len(collection.unassigned_vlm_ids),
        ))
        collection_id = cursor.lastrowid
        
        # Insert unassigned VLM IDs
        for vlm_id in collection.unassigned_vlm_ids:
            cursor.execute("""
                INSERT INTO eq_collection_unassigned (collection_id, vlm_id)
                VALUES (?, ?)
            """, (collection_id, vlm_id))
            self._unassigned_vlm_ids.add(vlm_id)
        
        # Insert each map
        for map_key, eq_map in collection.maps.items():
            self._export_map(cursor, collection_id, map_key, eq_map)
        
        self.conn.commit()
        return collection_id
    
    def _export_map(
        self,
        cursor: sqlite3.Cursor,
        collection_id: int,
        map_key: str,
        eq_map: MetalLigandEquilibriumMap,
    ) -> int:
        """Export a single map."""
        # Condition data
        cond = eq_map.condition
        cond_temp = cond.temperature if cond else None
        cond_ionic = cond.ionic_strength if cond else None
        cond_temp_min = cond.temp_range[0] if cond else None
        cond_temp_max = cond.temp_range[1] if cond else None
        cond_ionic_min = cond.ionic_range[0] if cond else None
        cond_ionic_max = cond.ionic_range[1] if cond else None
        iteration = cond.iteration if cond else 0
        
        cursor.execute("""
            INSERT INTO eq_map (
                collection_id, map_key, iteration,
                condition_temperature, condition_ionic_strength,
                condition_temp_min, condition_temp_max,
                condition_ionic_min, condition_ionic_max,
                entry_count, network_count, stray_count
            ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
        """, (
            collection_id, map_key, iteration,
            cond_temp, cond_ionic,
            cond_temp_min, cond_temp_max,
            cond_ionic_min, cond_ionic_max,
            len(eq_map.source_vlm_ids),
            len(eq_map.networks),
            len(eq_map.stray_vlm_ids),
        ))
        map_id = cursor.lastrowid
        
        # Insert stray VLM IDs
        for vlm_id in eq_map.stray_vlm_ids:
            cursor.execute("""
                INSERT INTO eq_map_stray (map_id, vlm_id)
                VALUES (?, ?)
            """, (map_id, vlm_id))
            self._stray_vlm_ids.add(vlm_id)
        
        # Insert networks
        for network_id, network in eq_map.networks.items():
            self._export_network(cursor, map_id, network)
        
        return map_id
    
    def _export_network(
        self,
        cursor: sqlite3.Cursor,
        map_id: int,
        network: EquilibriumNetwork,
    ) -> int:
        """Export a single network."""
        cursor.execute("""
            INSERT INTO eq_network (map_id, network_id, node_count, edge_count)
            VALUES (?, ?, ?, ?)
        """, (
            map_id,
            network.network_id,
            len(network.nodes),
            len(network.edges),
        ))
        network_db_id = cursor.lastrowid
        
        # Insert network species
        for species in network.all_species:
            cursor.execute("""
                INSERT INTO eq_network_species (network_db_id, species)
                VALUES (?, ?)
            """, (network_db_id, species))
        
        # Insert nodes
        vlm_to_node_db_id = {}
        for node in network.nodes:
            node_db_id = self._export_node(cursor, network_db_id, node)
            vlm_to_node_db_id[node.vlm_id] = node_db_id
            self._assigned_vlm_ids.add(node.vlm_id)
        
        # Insert edges
        for edge in network.edges:
            self._export_edge(cursor, network_db_id, edge)
        
        return network_db_id
    
    def _export_node(
        self,
        cursor: sqlite3.Cursor,
        network_db_id: int,
        node: EquilibriumNode,
    ) -> int:
        """Export a single node."""
        cursor.execute("""
            INSERT INTO eq_node (
                network_db_id, vlm_id, entry_index,
                metal_id, ligand_id, beta_definition_id,
                beta_definition_name, equation_python,
                constant_type, constant_value,
                temperature, ionic_strength,
                is_duplicate, used_in_map
            ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
        """, (
            network_db_id,
            node.vlm_id,
            node.entry_index,
            node.metal_id,
            node.ligand_id,
            node.beta_definition_id,
            node.beta_definition_name,
            node.equation_python,
            node.constant_type,
            node.constant_value,
            node.temperature,
            node.ionic_strength,
            1 if node.is_duplicate else 0,
            1 if node.used_in_map else 0,
        ))
        node_db_id = cursor.lastrowid
        
        # Insert species
        for species in node.lhs_species:
            cursor.execute("""
                INSERT OR IGNORE INTO eq_node_species (node_db_id, species, side)
                VALUES (?, ?, 'LHS')
            """, (node_db_id, species))
        
        for species in node.rhs_species:
            cursor.execute("""
                INSERT OR IGNORE INTO eq_node_species (node_db_id, species, side)
                VALUES (?, ?, 'RHS')
            """, (node_db_id, species))
        
        return node_db_id
    
    def _export_edge(
        self,
        cursor: sqlite3.Cursor,
        network_db_id: int,
        edge: EquilibriumEdge,
    ) -> int:
        """Export a single edge."""
        cursor.execute("""
            INSERT INTO eq_edge (network_db_id, node1_vlm_id, node2_vlm_id)
            VALUES (?, ?, ?)
        """, (network_db_id, edge.node1_vlm_id, edge.node2_vlm_id))
        edge_db_id = cursor.lastrowid
        
        # Insert shared species
        for species in edge.shared_species:
            cursor.execute("""
                INSERT INTO eq_edge_species (edge_db_id, species)
                VALUES (?, ?)
            """, (edge_db_id, species))
        
        return edge_db_id
    
    def export_all(self, max_pairs: Optional[int] = None, max_iterations: int = 10000) -> DebugReport:
        """Export all metal-ligand pairs to the database.
        
        Args:
            max_pairs: Optional limit on number of pairs to process (for testing)
            max_iterations: Maximum iterations per pair (default 10000)
            
        Returns:
            DebugReport with coverage statistics
        """
        logger.info("export_all: Starting full export...")
        self.debug_report.start_time = datetime.now().isoformat()
        start_time = time.time()
        
        # Validate first (also detects no-species betas)
        print("Validating VLM entries...")
        self.validate_vlm_entries()
        
        # Get all pairs
        pairs = self.get_unique_metal_ligand_pairs()
        logger.info(f"export_all: Found {len(pairs)} unique metal-ligand pairs")
        
        if max_pairs:
            pairs = pairs[:max_pairs]
            logger.info(f"export_all: Limited to first {max_pairs} pairs")
        
        print(f"\nProcessing {len(pairs)} metal-ligand pairs (max_iterations={max_iterations})...")
        logger.info(f"export_all: Processing {len(pairs)} pairs with max_iterations={max_iterations}")
        
        # Process each pair
        pairs_with_data = 0
        pairs_empty = 0
        pairs_error = 0
        
        for i, (metal_id, ligand_id) in enumerate(pairs):
            if (i + 1) % 500 == 0 or i == 0:
                elapsed = time.time() - start_time
                rate = (i + 1) / elapsed if elapsed > 0 else 0
                eta = (len(pairs) - i - 1) / rate if rate > 0 else 0
                print(f"  [{i + 1}/{len(pairs)}] metal={metal_id}, ligand={ligand_id} | {elapsed:.0f}s elapsed, ETA {eta:.0f}s")
                logger.info(f"export_all: Progress [{i + 1}/{len(pairs)}] - {pairs_with_data} with data, {pairs_empty} empty, {pairs_error} errors")
            
            try:
                collection = build_equilibrium_maps_for_pair(
                    metal_id=metal_id,
                    ligand_id=ligand_id,
                    max_iterations=max_iterations,
                )
                
                if collection.total_entries > 0:
                    self.export_collection(collection)
                    pairs_with_data += 1
                else:
                    pairs_empty += 1
                    
            except Exception as e:
                pairs_error += 1
                logger.warning(f"export_all: Error processing M={metal_id}, L={ligand_id}: {e}")
                self.debug_report.processing_errors.append({
                    "metal_id": metal_id,
                    "ligand_id": ligand_id,
                    "error": str(e),
                })
        
        logger.info(f"export_all: Finished processing - {pairs_with_data} with data, {pairs_empty} empty, {pairs_error} errors")
        
        # Finalize debug report
        self.debug_report.vlm_assigned_to_networks = len(self._assigned_vlm_ids)
        self.debug_report.vlm_stray = len(self._stray_vlm_ids)
        self.debug_report.vlm_unassigned = len(self._unassigned_vlm_ids)
        
        self.debug_report.end_time = datetime.now().isoformat()
        self.debug_report.duration_seconds = time.time() - start_time
        
        logger.info(f"export_all: Complete in {self.debug_report.duration_seconds:.1f}s")
        logger.info(f"  VLM assigned to networks: {self.debug_report.vlm_assigned_to_networks}")
        logger.info(f"  VLM stray (duplicates): {self.debug_report.vlm_stray}")
        logger.info(f"  VLM unassigned: {self.debug_report.vlm_unassigned}")
        
        # Save metadata
        cursor = self.conn.cursor()
        for key, value in self.debug_report.to_dict().items():
            cursor.execute("""
                INSERT INTO eq_export_metadata (key, value) VALUES (?, ?)
            """, (key, json.dumps(value)))
        self.conn.commit()
        
        return self.debug_report
    
    def save_debug_report(self, path: Path = DEBUG_REPORT_PATH) -> None:
        """Save debug report to JSON file."""
        report_dict = self.debug_report.to_dict()
        
        # Add detailed lists
        report_dict["invalid_beta_vlm_ids"] = self.debug_report.invalid_beta_vlm_ids[:100]
        report_dict["invalid_metal_vlm_ids"] = self.debug_report.invalid_metal_vlm_ids[:100]
        report_dict["invalid_ligand_vlm_ids"] = self.debug_report.invalid_ligand_vlm_ids[:100]
        report_dict["no_species_beta_ids"] = self.debug_report.no_species_beta_ids
        report_dict["processing_errors"] = self.debug_report.processing_errors[:100]
        
        path.parent.mkdir(parents=True, exist_ok=True)
        with open(path, "w", encoding="utf-8") as f:
            json.dump(report_dict, f, indent=2)
        
        print(f"Debug report saved to: {path}")
    
    def save_non_converged_csv(self, path: Path = NON_CONVERGED_CSV_PATH) -> None:
        """Save non-converged VLM IDs to CSV file."""
        if not self._unassigned_vlm_ids:
            print("No non-converged entries to save.")
            return
        
        # Load VLM data for additional info
        vlm_df = load_vlm_data()
        
        # Get rows for unassigned VLM IDs
        unassigned_df = vlm_df[vlm_df["verkn_ligand_metalID"].isin(self._unassigned_vlm_ids)].copy()
        
        # Select relevant columns
        cols = [
            "verkn_ligand_metalID", "metalNr", "ligandenNr", "beta_definitionNr",
            "constanttypNr", "constant", "temperature", "ionicstrength"
        ]
        out_df = unassigned_df[[c for c in cols if c in unassigned_df.columns]]
        out_df.to_csv(path, index=False)
        print(f"Non-converged VLM IDs saved to: {path} ({len(out_df)} entries)")
    
    def save_no_species_csv(self, path: Path = NO_SPECIES_CSV_PATH) -> None:
        """Save no-species VLM IDs to CSV file."""
        if not self.debug_report.no_species_vlm_ids:
            print("No no-species entries to save.")
            return
        
        # Load VLM data for additional info
        vlm_df = load_vlm_data()
        
        # Get rows for no-species VLM IDs
        no_species_df = vlm_df[vlm_df["verkn_ligand_metalID"].isin(self.debug_report.no_species_vlm_ids)].copy()
        
        # Select relevant columns
        cols = [
            "verkn_ligand_metalID", "metalNr", "ligandenNr", "beta_definitionNr",
            "constanttypNr", "constant", "temperature", "ionicstrength"
        ]
        out_df = no_species_df[[c for c in cols if c in no_species_df.columns]]
        out_df.to_csv(path, index=False)
        print(f"No-species VLM IDs saved to: {path} ({len(out_df)} entries)")


